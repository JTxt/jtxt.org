var VERT = 'attribute vec2 a_position; varying vec2 v_uv;' +
  'void main(){ v_uv = a_position*0.5+0.5; gl_Position = vec4(a_position,0.0,1.0); }';

var BOX_FRAG = [
  'precision highp float;',
  'varying vec2 v_uv;',
  'uniform sampler2D u_src; uniform vec2 u_texel; uniform vec2 u_region; uniform vec2 u_srcMax; uniform float u_off;',
  'vec3 tap(vec2 uv){ vec3 c = texture2D(u_src, clamp(uv, u_texel*0.5, u_srcMax)).rgb; return c*c; }',
  'void main(){',
  '  vec2 c = v_uv*u_region; vec2 o = u_texel*u_off;',
  '  vec3 s = tap(c+vec2(-o.x,-o.y)) + tap(c+vec2(o.x,-o.y)) + tap(c+vec2(-o.x,o.y)) + tap(c+vec2(o.x,o.y));',
  '  gl_FragColor = vec4(sqrt(s*0.25), 1.0);',
  '}'
].join('\n');

var GAUSS_FRAG = [
  'precision highp float;',
  'varying vec2 v_uv;',
  'uniform sampler2D u_src; uniform vec2 u_texel; uniform vec2 u_region; uniform vec2 u_srcMax;',
  'uniform vec2 u_dir; uniform float u_radius;',
  'vec3 tap(vec2 uv, float w){ vec3 c = texture2D(u_src, clamp(uv, u_texel*0.5, u_srcMax)).rgb; return c*c*w; }',
  'void main(){',
  '  vec2 b = v_uv*u_region; vec2 d = u_texel*u_dir*(u_radius/6.0); vec3 s = vec3(0.0);',
  '  s += tap(b-6.0*d,0.01854); s += tap(b-5.0*d,0.03418); s += tap(b-4.0*d,0.05633);',
  '  s += tap(b-3.0*d,0.08312); s += tap(b-2.0*d,0.10972); s += tap(b-1.0*d,0.12961);',
  '  s += tap(b,0.13703);',
  '  s += tap(b+1.0*d,0.12961); s += tap(b+2.0*d,0.10972); s += tap(b+3.0*d,0.08312);',
  '  s += tap(b+4.0*d,0.05633); s += tap(b+5.0*d,0.03418); s += tap(b+6.0*d,0.01854);',
  '  gl_FragColor = vec4(sqrt(s), 1.0);',
  '}'
].join('\n');

var MAIN_FRAG = [
  'precision highp float;',
  'varying vec2 v_uv;',
  'uniform sampler2D u_image;',
  'uniform vec2 u_canvasSize; uniform vec2 u_imageSize; uniform vec2 u_pan;',
  'uniform float u_rotation; uniform float u_flipX; uniform float u_flipY;',
  'uniform float u_fitScale; uniform float u_zoom; uniform float u_bgAlpha;',
  'uniform vec3 u_bg;',
  'uniform float u_chroma; uniform float u_n; uniform float u_iso; uniform float u_grid; uniform float u_outL;',
  'uniform float u_th[8];',
  'uniform float u_tone[9];',
  '',
  'vec3 toOklab(vec3 c){',
  '  vec3 lin = c*c;',
  '  float l = dot(lin, vec3(0.4122214708, 0.5363325363, 0.0514459929));',
  '  float m = dot(lin, vec3(0.2119034982, 0.6806995451, 0.1073969566));',
  '  float s = dot(lin, vec3(0.0883024619, 0.2817188376, 0.6299787005));',
  '  vec3 q = pow(max(vec3(l,m,s), 0.0), vec3(0.3333333));',
  '  return vec3(dot(q, vec3(0.2104542553, 0.7936177850, -0.0040720468)),',
  '              dot(q, vec3(1.9779984951, -2.4285922050, 0.4505937099)),',
  '              dot(q, vec3(0.0259040371, 0.7827717662, -0.8086757660)));',
  '}',
  'vec3 fromOklab(vec3 lab){',
  '  float l_ = lab.x + 0.3963377774*lab.y + 0.2158037573*lab.z;',
  '  float m_ = lab.x - 0.1055613458*lab.y - 0.0638541728*lab.z;',
  '  float s_ = lab.x - 0.0894841775*lab.y - 1.2914855480*lab.z;',
  '  vec3 c = vec3(l_*l_*l_, m_*m_*m_, s_*s_*s_);',
  '  vec3 lin = vec3(dot(c, vec3(4.0767416621, -3.3077115913, 0.2309699292)),',
  '                  dot(c, vec3(-1.2684380046, 2.6097574011, -0.3413193965)),',
  '                  dot(c, vec3(-0.0041960863, -0.7034186147, 1.7076147010)));',
  '  return sqrt(clamp(lin, 0.0, 1.0));',
  '}',
  'float toLstar(float L){ float Y = L*L*L; return Y > 0.008856 ? 116.0*L - 16.0 : 903.3*Y; }',
  'float fromLstar(float s){ return s > 8.0 ? (s + 16.0)/116.0 : pow(max(s,0.0)/903.3, 0.3333333); }',
  '',
  'void main(){',
  '  vec2 ndc = v_uv*2.0 - 1.0;',
  '  vec2 p = (ndc*u_canvasSize*0.5 - u_pan) / max(u_zoom, 0.0001);',
  '  float c = cos(-u_rotation), s = sin(-u_rotation);',
  '  vec2 rp = vec2(p.x*c - p.y*s, p.x*s + p.y*c) / max(u_fitScale, 0.0001);',
  '  vec2 iuv = rp / u_imageSize * vec2(u_flipX, u_flipY) + 0.5;',
  '  if(iuv.x < 0.0 || iuv.x > 1.0 || iuv.y < 0.0 || iuv.y > 1.0){',
  '    gl_FragColor = vec4(u_bg*u_bgAlpha, u_bgAlpha); return;',
  '  }',
  '  vec3 lab = toOklab(texture2D(u_image, iuv).rgb);',
  '  float ls = toLstar(lab.x);',
  '  if(u_outL > 0.5){ gl_FragColor = vec4(vec3(clamp(ls/100.0, 0.0, 1.0)), 1.0); return; }',
  '  float band = 0.0;',
  '  if(u_n > 1.5){',
  '    for(int i = 0; i < 8; i++){ if(float(i) < u_n - 1.0 && ls > u_th[i]) band += 1.0; }',
  '    float t = 0.0;',
  '    for(int i = 0; i < 9; i++){ if(abs(float(i) - band) < 0.5) t = u_tone[i]; }',
  '    lab.x = fromLstar(t);',
  '  }',
  '  vec3 outc = fromOklab(vec3(lab.x, lab.yz*u_chroma));',
  '  if(u_n > 1.5 && u_iso > -0.5 && abs(band - u_iso) > 0.5){ outc = mix(outc, u_bg, 0.86); }',
  '  if(u_grid > 0.5){',
  '    vec2 d = abs(fract(iuv*u_grid + 0.5) - 0.5) / u_grid;',
  '    vec2 px = 1.0 / (max(u_fitScale*u_zoom, 0.0001) * u_imageSize);',
  '    float on = max(step(d.x, px.x*0.8), step(d.y, px.y*0.8));',
  '    float y = dot(outc*outc, vec3(0.2126, 0.7152, 0.0722));',
  '    outc = mix(outc, y > 0.18 ? vec3(0.0) : vec3(1.0), on*0.7);',
  '  }',
  '  gl_FragColor = vec4(outc, 1.0);',
  '}'
].join('\n');

// Drawing Check: the reference (plain, or squinted by the Squint pipeline), with
// the drawing's lines drawn from a distance field (distance to the nearest line,
// per texel), so they stay smooth at any zoom. Fade (u_mix) brings the drawing
// photo in over the reference as the outline goes out. Mode 1 draws the drawing
// photo alone and mode 2 the reference alone, both for the side-by-side save.
var CHECK_FRAG = [
  'precision highp float;',
  'varying vec2 v_uv;',
  'uniform sampler2D u_ref; uniform sampler2D u_draw; uniform sampler2D u_line;',
  'uniform mat3 u_toRef; uniform mat3 u_refToDraw;',
  'uniform vec3 u_bg; uniform float u_mode; uniform float u_mix;',
  'uniform float u_hasDraw; uniform float u_hasLine;',
  'uniform float u_w; uniform float u_halo; uniform float u_aa; uniform float u_maxD;',
  'uniform vec3 u_ink; uniform vec3 u_haloC;',
  'uniform vec4 u_frame; uniform float u_frameOn;',
  'uniform float u_grid; uniform vec2 u_gridPx;',
  'bool inside(vec2 p){ return p.x >= 0.0 && p.x <= 1.0 && p.y >= 0.0 && p.y <= 1.0; }',
  // The same grid Squint draws: black on light passages, white on dark ones.
  'vec3 gridOver(vec3 c, vec2 r){',
  '  if(u_grid < 0.5) return c;',
  '  vec2 d = abs(fract(r*u_grid + 0.5) - 0.5) / u_grid;',
  '  float on = max(step(d.x, u_gridPx.x*0.8), step(d.y, u_gridPx.y*0.8));',
  '  float y = dot(c*c, vec3(0.2126, 0.7152, 0.0722));',
  '  return mix(c, y > 0.18 ? vec3(0.0) : vec3(1.0), on*0.7);',
  '}',
  'void main(){',
  '  vec2 r = (u_toRef * vec3(v_uv, 1.0)).xy;',
  '  vec2 d = (u_refToDraw * vec3(r, 1.0)).xy;',
  '  bool inRef = inside(r), inDraw = u_hasDraw > 0.5 && inside(d);',
  '  if(u_mode > 0.5 && u_mode < 1.5){',
  '    vec3 pc = inDraw ? texture2D(u_draw, d).rgb : vec3(1.0);',
  '    gl_FragColor = vec4(inRef ? gridOver(pc, r) : pc, 1.0); return;',
  '  }',
  '  vec3 c = inRef ? texture2D(u_ref, r).rgb : u_bg;',
  '  if(u_mode > 1.5){ gl_FragColor = vec4(inRef ? gridOver(c, r) : c, 1.0); return; }',
  '  if(inDraw) c = mix(c, texture2D(u_draw, d).rgb, u_mix);',
  '  if(inRef) c = gridOver(c, r);',
  '  if(u_hasLine > 0.5 && inDraw){',
  '    float dist = texture2D(u_line, d).r * u_maxD, a = 1.0 - u_mix;',
  '    float line = 1.0 - smoothstep(u_w - u_aa, u_w + u_aa, dist);',
  '    float halo = 1.0 - smoothstep(u_w + u_halo - u_aa, u_w + u_halo + u_aa, dist);',
  '    c = mix(c, u_haloC, halo*0.8*a);',
  '    c = mix(c, u_ink, line*a);',
  '  }',
  '  if(u_frameOn > 0.5 && (r.x < u_frame.x || r.x > u_frame.z || r.y < u_frame.y || r.y > u_frame.w)) c = mix(c, u_bg, 0.6);',
  '  gl_FragColor = vec4(c, 1.0);',
  '}'
].join('\n');
